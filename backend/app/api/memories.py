"""Memory management API (Phase 2, Step 6).

Backend interfaces for reviewing, correcting, and deleting stored memories.
No UI lives here; the routes are thin wrappers over `memory_service`, which
owns the storage rules and the lifecycle/audit behavior.

Routes:
- GET    /api/memories                 list with status/kind/origin filters
- GET    /api/memories/{id}            one memory + validated provenance/history
- POST   /api/memories/{id}/confirm    review|accepted -> confirmed
- POST   /api/memories/{id}/reject     review -> deleted (rejected candidate)
- PATCH  /api/memories/{id}            correct statement/subject/keywords
- DELETE /api/memories/{id}            soft delete (idempotent, 204)

Trust rules enforced here:
- Clients never choose a lifecycle target status; each endpoint defines the
  only transition it performs (409 when the current status is not eligible).
- Clients cannot submit origin, confidence, ids, or source references: the
  request models reject unknown fields, and corrections only accept
  statement/subject/keywords.
- Provenance is returned only after validation against the real conversation
  and message rows. Message-bearing records are invalid when any declared
  message is missing or belongs to another conversation; stale or mismatched
  ids are omitted, surviving ids are shown for audit, and `valid` is false.
  Conversation-only legacy records remain valid while their conversation
  exists.
- Deletion is a soft delete: the row and its history remain, retrieval excludes
  it immediately, and source conversations/messages are never touched.

Errors are mapped to safe messages; logs contain only the operation and the
exception class name (never memory text or database paths).
"""

import logging
import sqlite3
from typing import Annotated

from fastapi import APIRouter, HTTPException, Path, Query, Request

from ..config import (
    DEFAULT_MEMORY_PAGE_SIZE,
    MAX_MEMORY_HISTORY_ENTRIES,
    MAX_MEMORY_PAGE_SIZE,
)
from ..db.connection import db_connection
from ..models.schemas import (
    MemoryApiOut,
    MemoryCorrectionIn,
    MemoryDetailOut,
    MemoryKind,
    MemoryListOut,
    MemoryOrigin,
    MemoryOut,
    MemoryProvenanceOut,
    MemoryReviewIn,
    MemoryStatus,
)
from ..services.memory_service import (
    MemoryNotFound,
    MemoryPersistenceError,
    MemoryTransitionError,
    confirm_memory,
    correct_memory,
    delete_memory,
    ensure_memory_editable,
    get_memory_history,
    list_memories,
    memory_provenance,
    reject_memory,
    require_memory,
    supersede_memory,
)

logger = logging.getLogger(__name__)

router = APIRouter()

# Memory ids are generated by `new_id()` (uuid4().hex): 32 lowercase hex chars.
MemoryId = Annotated[
    str,
    Path(
        pattern=r"^[0-9a-f]{32}$",
        description="Stable 32-character hexadecimal memory id.",
    ),
]


def _storage_failure(exc: Exception, detail: str) -> HTTPException:
    """Log the failure class only and return a safe 500 response."""
    logger.warning("Memory API failure (%s): %s", detail, exc.__class__.__name__)
    return HTTPException(status_code=500, detail=detail)


# History snapshots are audit records of content/status. Source references are
# immutable and already exposed (validated) in `provenance`, so the raw stored
# fields are stripped here: a stale reference must never reappear through an
# old snapshot as if it were a usable source.
_HISTORY_REDACTED_KEYS = frozenset({"source_conversation_id", "source_message_ids"})


def _sanitize_history_value(value):
    if isinstance(value, dict):
        return {
            key: _sanitize_history_value(item)
            for key, item in value.items()
            if key not in _HISTORY_REDACTED_KEYS
        }
    if isinstance(value, list):
        return [_sanitize_history_value(item) for item in value]
    return value


def _api_memory(memory: MemoryOut, provenance: MemoryProvenanceOut) -> MemoryApiOut:
    return MemoryApiOut(
        id=memory.id,
        kind=memory.kind,
        statement=memory.statement,
        subject=memory.subject,
        keywords=memory.keywords,
        origin=memory.origin,
        status=memory.status,
        confidence=memory.confidence,
        provenance=provenance,
        created_at=memory.created_at,
        updated_at=memory.updated_at,
        last_confirmed_at=memory.last_confirmed_at,
    )


def _load_one(conn: sqlite3.Connection, memory_id: str) -> MemoryApiOut:
    """Read one memory plus validated provenance (shared by transitions)."""
    memory = require_memory(conn, memory_id)
    provenance = memory_provenance(conn, [memory])[memory.id]
    return _api_memory(memory, provenance)


@router.get("/api/memories", response_model=MemoryListOut)
async def list_memories_endpoint(
    request: Request,
    status: MemoryStatus | None = Query(default=None),
    kind: MemoryKind | None = Query(default=None),
    origin: MemoryOrigin | None = Query(default=None),
    limit: int = Query(default=DEFAULT_MEMORY_PAGE_SIZE, ge=1, le=MAX_MEMORY_PAGE_SIZE),
    offset: int = Query(default=0, ge=0),
) -> MemoryListOut:
    """One bounded page of memories, newest activity first.

    All lifecycle statuses are listable (including `deleted`) so a review
    client can audit them; filters are optional and combine with AND.
    """
    settings = request.app.state.settings
    with db_connection(settings.db_path) as conn:
        try:
            memories, total = list_memories(
                conn,
                status=status,
                kind=kind,
                origin=origin,
                limit=limit,
                offset=offset,
            )
            provenance = memory_provenance(conn, memories)
        except (MemoryPersistenceError, sqlite3.Error) as exc:
            raise _storage_failure(exc, "Could not read memories.") from exc
    return MemoryListOut(
        items=[_api_memory(memory, provenance[memory.id]) for memory in memories],
        total=total,
        limit=limit,
        offset=offset,
    )


@router.get("/api/memories/{memory_id}", response_model=MemoryDetailOut)
async def get_memory_endpoint(memory_id: MemoryId, request: Request) -> MemoryDetailOut:
    """One memory with validated sources and a bounded history window."""
    settings = request.app.state.settings
    with db_connection(settings.db_path) as conn:
        try:
            memory = require_memory(conn, memory_id)
            provenance = memory_provenance(conn, [memory])[memory.id]
            history = get_memory_history(
                conn, memory_id, limit=MAX_MEMORY_HISTORY_ENTRIES
            )
        except MemoryNotFound as exc:
            raise HTTPException(status_code=404, detail="Memory not found.") from exc
        except (MemoryPersistenceError, sqlite3.Error) as exc:
            raise _storage_failure(exc, "Could not read the memory.") from exc
    return MemoryDetailOut(
        **_api_memory(memory, provenance).model_dump(),
        history=[
            entry.model_copy(update={"value": _sanitize_history_value(entry.value)})
            for entry in history
        ],
    )


@router.post("/api/memories/{memory_id}/confirm", response_model=MemoryApiOut)
async def confirm_memory_endpoint(
    memory_id: MemoryId, request: Request, payload: MemoryReviewIn | None = None
) -> MemoryApiOut:
    """Confirm an accepted or review-pending memory.

    Confirmation never changes origin, confidence, or provenance; an inferred
    memory remains labelled inferred in prompts after confirmation.
    """
    settings = request.app.state.settings
    with db_connection(settings.db_path) as conn:
        try:
            confirm_memory(conn, memory_id, payload.reason if payload else None)
            return _load_one(conn, memory_id)
        except MemoryNotFound as exc:
            raise HTTPException(status_code=404, detail="Memory not found.") from exc
        except MemoryTransitionError as exc:
            raise HTTPException(status_code=409, detail=str(exc)) from exc
        except (MemoryPersistenceError, sqlite3.Error) as exc:
            raise _storage_failure(exc, "Could not confirm the memory.") from exc


@router.post("/api/memories/{memory_id}/reject", response_model=MemoryApiOut)
async def reject_memory_endpoint(
    memory_id: MemoryId, request: Request, payload: MemoryReviewIn | None = None
) -> MemoryApiOut:
    """Reject a review-pending candidate.

    Rejection is stored as a soft delete with a reason in the history; the
    candidate is excluded from all future retrieval.
    """
    settings = request.app.state.settings
    with db_connection(settings.db_path) as conn:
        try:
            reject_memory(conn, memory_id, payload.reason if payload else None)
            return _load_one(conn, memory_id)
        except MemoryNotFound as exc:
            raise HTTPException(status_code=404, detail="Memory not found.") from exc
        except MemoryTransitionError as exc:
            raise HTTPException(status_code=409, detail=str(exc)) from exc
        except (MemoryPersistenceError, sqlite3.Error) as exc:
            raise _storage_failure(exc, "Could not reject the memory.") from exc


@router.post("/api/memories/{memory_id}/supersede", response_model=MemoryApiOut)
async def supersede_memory_endpoint(
    memory_id: MemoryId, request: Request, payload: MemoryReviewIn | None = None
) -> MemoryApiOut:
    """Mark an accepted/confirmed memory outdated (retained for audit).

    `superseded` records are excluded from retrieval and prompt evidence. The
    record, provenance, and history remain inspectable and exportable.
    """
    settings = request.app.state.settings
    with db_connection(settings.db_path) as conn:
        try:
            supersede_memory(conn, memory_id, payload.reason if payload else None)
            return _load_one(conn, memory_id)
        except MemoryNotFound as exc:
            raise HTTPException(status_code=404, detail="Memory not found.") from exc
        except MemoryTransitionError as exc:
            raise HTTPException(status_code=409, detail=str(exc)) from exc
        except (MemoryPersistenceError, sqlite3.Error) as exc:
            raise _storage_failure(exc, "Could not update the memory.") from exc


@router.patch("/api/memories/{memory_id}", response_model=MemoryApiOut)
async def correct_memory_endpoint(
    memory_id: MemoryId, payload: MemoryCorrectionIn, request: Request
) -> MemoryApiOut:
    """Correct editable content; the previous value is kept in history.

    Only statement/subject/keywords can change. Corrections never modify
    provenance, origin, status, source messages, or other memories.
    """
    settings = request.app.state.settings
    with db_connection(settings.db_path) as conn:
        try:
            memory = require_memory(conn, memory_id)
            ensure_memory_editable(memory)
            correct_memory(conn, memory_id, payload)
            return _load_one(conn, memory_id)
        except MemoryNotFound as exc:
            raise HTTPException(status_code=404, detail="Memory not found.") from exc
        except MemoryTransitionError as exc:
            raise HTTPException(status_code=409, detail=str(exc)) from exc
        except ValueError as exc:
            raise HTTPException(
                status_code=422,
                detail="A correction must change at least one of statement, subject, or keywords.",
            ) from exc
        except (MemoryPersistenceError, sqlite3.Error) as exc:
            raise _storage_failure(exc, "Could not correct the memory.") from exc


@router.delete("/api/memories/{memory_id}", status_code=204)
async def delete_memory_endpoint(memory_id: MemoryId, request: Request) -> None:
    """Soft-delete a memory. Idempotent; source data is never deleted."""
    settings = request.app.state.settings
    with db_connection(settings.db_path) as conn:
        try:
            delete_memory(conn, memory_id)
        except MemoryNotFound as exc:
            raise HTTPException(status_code=404, detail="Memory not found.") from exc
        except (MemoryPersistenceError, sqlite3.Error) as exc:
            raise _storage_failure(exc, "Could not delete the memory.") from exc
